const STRINGS: Record<Lang, Record<StringKey, string>> = { en, hi, mr };
const STORAGE_KEY = "km_lang";

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "hi" || saved === "mr" || saved === "en") return saved;
  } catch { /* storage unavailable */ }
  return "hi";
}

let current: Lang = initialLang();
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
  listeners.forEach(l => l());
}

export function t(key: StringKey, vars?: Record<string, string | number>): string {
  let text = STRINGS[current][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

/** Re-render the component when the language changes; returns the active language. */
export function useLang(): Lang {
  return useSyncExternalStore(
    cb => { listeners.add(cb); return () => listeners.delete(cb); },
    getLang,
  );
}

/** Translate a backend error code (e.g. "invalid_code"), falling back to a generic message. */
export function errorText(code: string | undefined): string {
  const key = `err_${code}` as StringKey;
  return key in en ? t(key) : t("err_generic");
}

